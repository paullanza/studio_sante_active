require "rails_helper"

RSpec.describe PhoneHelper, type: :helper do
  {
    "+15145550142"   => [ "(514) 555-0142", "tel:+15145550142" ],
    "514-555-0142"   => [ "(514) 555-0142", "tel:+15145550142" ],
    "1 514 555 0142" => [ "(514) 555-0142", "tel:+15145550142" ],
    "+4385550142"    => [ "(438) 555-0142", "tel:+14385550142" ],
    "+33612345678"   => [ "+33 6 12 34 56 78", "tel:+33612345678" ],
    "06 12 34 56 78" => [ "+33 6 12 34 56 78", "tel:+33612345678" ],
    "0033612345678"  => [ "+33 6 12 34 56 78", "tel:+33612345678" ],
    "+105145550142"  => [ "(514) 555-0142", "tel:+15145550142" ],
    "+11514555014"   => [ "+11514555014", nil ],
    "+447700900123"  => [ "+44 7700900123", "tel:+447700900123" ],
    "+351912345678"  => [ "+351 912345678", "tel:+351912345678" ],
    "+5561912345678" => [ "+55 61912345678", "tel:+5561912345678" ],
    "+8613812345678" => [ "+8613812345678", "tel:+8613812345678" ],
    "(143)555-0142"  => [ "(143)555-0142", nil ],
    "us"             => [ "us", nil ],
    "-"              => [ "-", nil ],
    "0"              => [ "0", nil ],
    "123456789"      => [ "123456789", nil ]
  }.each do |raw, (shown, href)|
    it "shows #{raw.inspect} as #{shown.inspect}" do
      expect(helper.format_phone(raw)).to eq(shown)
      expect(helper.phone_href(raw)).to eq(href)
    end
  end

  it "handles a missing number" do
    expect(helper.format_phone(nil)).to eq("")
    expect(helper.phone_href(nil)).to be_nil
  end
end
